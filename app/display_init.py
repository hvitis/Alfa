"""ST7789 setup shared by the Linux driver and firmware splash preparation."""


def st7789_commands(display):
    """Yield (command, parameter bytes, delay in microseconds after the command)."""
    return (
        (0x01, b"", 150000),  # Software reset.
        (0x11, b"", 120000),  # Exit sleep.
        (0x36, bytes([0x08 if display["bgr"] else 0x00]), 0),
        (0x3A, b"\x55", 0),  # RGB565.
        (0xB2, bytes([0x0C, 0x0C, 0x00, 0x33, 0x33]), 0),
        (0xB7, b"\x35", 0),
        (0xBB, b"\x1f", 0),
        (0xC0, b"\x2c", 0),
        (0xC2, b"\x01", 0),
        (0xC3, b"\x12", 0),
        (0xC4, b"\x20", 0),
        (0xC6, b"\x0f", 0),
        (0xD0, bytes([0xA4, 0xA1]), 0),
        (0xE0, bytes([0xD0, 0x08, 0x11, 0x08, 0x0C, 0x15, 0x39, 0x33, 0x50, 0x36, 0x13, 0x14, 0x29, 0x2D]), 0),
        (0xE1, bytes([0xD0, 0x08, 0x10, 0x08, 0x06, 0x06, 0x39, 0x44, 0x51, 0x0B, 0x16, 0x14, 0x2F, 0x31]), 0),
        (0x21 if display["invert"] else 0x20, b"", 0),
        (0x13, b"", 0),
        (0x29, b"", 20000),
    )
