export function getLocale() {
  if (typeof document === 'undefined') return 'en';
  return document.documentElement.lang === 'en' ? 'en' : 'pl';
}

export function t(key, vars = {}) {
  const lang = getLocale();
  let text = messages[lang]?.[key] ?? messages.en[key];
  if (text == null) return key;
  for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

export function tr(text) {
  if (typeof text !== 'string' || getLocale() !== 'pl') return text;
  if (Object.prototype.hasOwnProperty.call(glossary, text)) return glossary[text];
  if (text.startsWith('http://') || text.startsWith('https://')) return text;
  let out = text;
  for (const [from, to] of fragments) out = out.replaceAll(from, to);
  return out;
}
